#!/usr/bin/env python3
"""Sync homepage publication cards to the web CV and standalone LaTeX CV."""

import json
import re
from html.parser import HTMLParser
from pathlib import Path


class Node:
    def __init__(self, tag="", attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def text(self):
        return "".join(c if isinstance(c, str) else c.text() for c in self.children)

    def nodes(self):
        for child in self.children:
            if isinstance(child, Node):
                yield child
                yield from child.nodes()

    def with_class(self, name):
        return next(n for n in self.nodes() if name in n.attrs.get("class", "").split())


class CardParser(HTMLParser):
    def __init__(self, source):
        super().__init__()
        self.root = Node()
        self.stack = [self.root]
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in {"img", "br", "source", "hr", "input", "meta", "link"}:
            self.stack.append(node)

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def clean(text):
    return re.sub(r"\s+", " ", text).strip(" ,")


def parse_publications(source):
    cards = re.findall(
        r'<article\b[^>]*class="[^"]*\bpublication-row\b[^"]*"[^>]*>.*?</article>',
        source,
        re.DOTALL,
    )
    publications = []
    for card in cards:
        root = CardParser(card).root
        article = next(n for n in root.nodes() if n.tag == "article")
        title = root.with_class("papertitle")
        authors = clean(root.with_class("card-authors").text())
        venues = [n for n in root.nodes() if "card-venue" in n.attrs.get("class", "").split()]
        venue = clean(venues[0].text()) if venues else ""
        links = [
            (clean(n.text()), n.attrs["href"])
            for n in root.with_class("publication-links").nodes()
            if n.tag == "a" and "href" in n.attrs
        ]
        if article.attrs.get("data-category") == "position":
            publisher, kind = "Position paper", "position"
        elif "Competition" in venue:
            publisher, kind = "NeurIPS Competition Report", "competition-report"
        elif "SIGGRAPH" in venue:
            publisher, kind = "ACM SIGGRAPH Asia", "conference"
        elif "TPAMI" in venue:
            publisher, kind = "IEEE TPAMI", "journal"
        elif "ICML" in venue:
            publisher, kind = "ICML" + (" Poster" if "Poster" in venue else ""), "conference"
        elif "ICLR" in venue:
            publisher, kind = "ICLR" + (" Poster" if "Poster" in venue else ""), "conference"
        elif "RSS" in venue:
            publisher, kind = "RSS", "conference"
        elif "arXiv" in venue or any("arxiv.org/" in url for _, url in links):
            publisher, kind = "arXiv preprint", "preprint"
        else:
            raise ValueError(f"Review publication status for {clean(title.text())!r}")

        entry = {
            "name": clean(title.text()),
            "publisher": publisher,
            "releaseDate": article.attrs["data-year"],
            "authors": authors,
            "type": kind,
        }
        # The Sim2Real-VLA title links to its own OpenReview paper; its action
        # link currently duplicates DexScale's paper. Prefer the title there.
        if "openreview.net/" in title.attrs.get("href", ""):
            entry["website"] = title.attrs["href"]
        else:
            for label in ("arXiv", "Paper", "Report", "PDF", "Project", "Website"):
                match = next((url for text, url in links if text == label), None)
                if match:
                    entry["website"] = match
                    break
        publications.append(entry)
    if not publications:
        raise ValueError("No homepage publications found; refusing to replace the CV list.")
    return publications


def tex_escape(text):
    chars = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
             "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
             "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}
    return "".join(chars.get(char, char) for char in text)


def render_latex(publications):
    lines = [
        "% Generated by scripts/sync_cv_publications.py from _pages/about.md.",
        "% Committed with the CV so resume/ remains independently compilable.",
        r"\begin{rSection}{Publications and Reports}",
        r"{\fontsize{9.5}{11.8}\selectfont",
        r"\begin{itemize}[leftmargin=1.8em,labelsep=0.5em,itemsep=5pt,topsep=1pt,parsep=0pt]",
    ]
    for index, entry in enumerate(publications):
        authors = tex_escape(entry["authors"]).replace("Yueci Deng", r"\textbf{Yueci Deng}")
        authors = authors.replace("*", r"\textsuperscript{*}").replace("†", r"\textsuperscript{$\dagger$}")
        title = r"\textbf{" + tex_escape(entry["name"]) + "}"
        if entry.get("website"):
            title = r"\href{" + tex_escape(entry["website"]) + "}{" + title + "}"
        lines.append(r"\item[{\scriptsize\color{cvMuted}" + str(len(publications) - index)
                     + ".}] " + title + r"\\[-1pt]" + "\n"
                     + r"{\color{cvMuted}" + authors + ".} "
                     + r"\textit{" + tex_escape(entry["publisher"]) + ",~"
                     + entry["releaseDate"] + ".}")
    lines += [r"\end{itemize}",
              r"{\fontsize{8.5}{10}\selectfont\color{cvMuted}* Equal contribution. $\dagger$ Corresponding author.\par}",
              "}", r"\end{rSection}", ""]
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parent.parent
    publications = parse_publications((root / "_pages/about.md").read_text(encoding="utf-8"))
    data_path = root / "_data/cv.json"
    data = json.loads(data_path.read_text(encoding="utf-8"))
    data["publications"] = publications
    data_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (root / "resume/publications.tex").write_text(render_latex(publications), encoding="utf-8")
    print(f"Synced {len(publications)} homepage publications to the web and LaTeX CVs.")


if __name__ == "__main__":
    main()
